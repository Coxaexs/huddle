export function localizeAchievement(def: AchievementDef, locale: string): AchievementDef {
  if (locale !== "tr") return def;
  const tr = TR_ACHIEVEMENTS[def.id];
  if (!tr) return def;
  return { ...def, label: tr.label, description: tr.description, hint: tr.hint ?? def.hint };
}

export function localizeAchievementCategory(id: AchievementCategory, fallback: string, locale: string): string {
  if (locale !== "tr") return fallback;
  return TR_ACHIEVEMENT_CATEGORIES[id] ?? fallback;
}
